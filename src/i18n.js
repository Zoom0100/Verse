let lang = "en";
const listeners = new Set();

export function t(key) {
  return STR[lang]?.[key] ?? STR.en[key] ?? key;
}

export function onLang(fn) {
  listeners.add(fn);
}

export function isDefaultMaint(text) {
  return LANGS.some((item) => STR[item.id].maintDefault === text);
}

export function setLanguage(id) {
  if (!STR[id]) return;
  lang = id;
  localStorage.setItem(KEY, id);
  document.documentElement.lang = id === "zh" ? "zh-Hans" : id;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  listeners.forEach((fn) => fn());
}

export function initLanguage() {
  const saved = localStorage.getItem(KEY);
  const nav = (navigator.language || "en").toLowerCase();
  const guess = LANGS.find((item) => nav.startsWith(item.id) || (item.id === "fil" && nav.startsWith("tl")));
  setLanguage(saved || guess?.id || "en");
}
